CREATE TABLE IF NOT EXISTS bus_telemetry (
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    bus_id UUID NOT NULL REFERENCES buses(id) ON DELETE CASCADE,
    route_id UUID REFERENCES routes(id) ON DELETE SET NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    location GEOGRAPHY(Point, 4326) NOT NULL,
    speed_kmh DOUBLE PRECISION NOT NULL DEFAULT 0,
    heading_deg DOUBLE PRECISION NOT NULL DEFAULT 0,
    occupancy INT NOT NULL DEFAULT 0
);

SELECT create_hypertable('bus_telemetry', 'recorded_at', if_not_exists => TRUE);

CREATE INDEX IF NOT EXISTS idx_bus_telemetry_tenant_bus_time ON bus_telemetry (tenant_id, bus_id, recorded_at DESC);

ALTER TABLE bus_telemetry ENABLE ROW LEVEL SECURITY;
ALTER TABLE bus_telemetry FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation_policy ON bus_telemetry;
CREATE POLICY tenant_isolation_policy ON bus_telemetry
    FOR ALL
    TO app_user
    USING (CASE WHEN current_setting('app.current_tenant', true) = 'SUPER_ADMIN' THEN true ELSE tenant_id = NULLIF(current_setting('app.current_tenant', true), '')::uuid END)
    WITH CHECK (CASE WHEN current_setting('app.current_tenant', true) = 'SUPER_ADMIN' THEN true ELSE tenant_id = NULLIF(current_setting('app.current_tenant', true), '')::uuid END);

GRANT SELECT, INSERT ON bus_telemetry TO app_user;

